CREATE TABLE housing_prices (
	id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	date TIMESTAMP NOT NULL,
	price NUMERIC(12, 2) NOT NULL,
	bedrooms SMALLINT NOT NULL,
	bathrooms DOUBLE PRECISION NOT NULL,
	sqft_living INTEGER NOT NULL,
	sqft_lot INTEGER NOT NULL,
	floors DOUBLE PRECISION NOT NULL,
	waterfront SMALLINT NOT NULL,
	view SMALLINT NOT NULL,
	condition SMALLINT NOT NULL,
	sqft_above INTEGER NOT NULL,
	sqft_basement INTEGER NOT NULL,
	yr_built SMALLINT NOT NULL,
	yr_renovated SMALLINT NOT NULL,
	street VARCHAR(50) NOT NULL,
	city VARCHAR(50) NOT NULL,
	statezip VARCHAR(10) NOT NULL,
	country VARCHAR(12) NOT NULL
)